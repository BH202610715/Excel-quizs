BANK = {'하': {'mc': [], 'sa': []}, '중': {'mc': [], 'sa': []}, '상': {'mc': [], 'sa': []}}


def add_mc(level, topic, kind, prompt, answer, distractors, explanation):
    opts = list(dict.fromkeys([str(answer)] + [str(x) for x in distractors if str(x) != str(answer)]))
    # 문항마다 4개 선택지를 보장하고, 오답은 짧은 학습 가능한 혼동항목으로 채운다.
    filler = ['함수 인수의 순서를 바꾼다', '조건에 맞는 셀을 센다', '범위의 합계를 구한다', '현재 날짜와 시간을 반환한다', '텍스트의 길이를 센다']
    for x in filler:
        if len(opts) >= 4: break
        if x not in opts: opts.append(x)
    opts = opts[:4]
    if answer not in opts:
        opts[-1] = str(answer)
    RNG.shuffle(opts)
    BANK[level]['mc'].append({'type':'객관식','topic':topic,'kind':kind,'prompt':prompt,'options':opts,'answer':str(answer),'explanation':explanation})


def add_sa(level, topic, kind, prompt, answer, accepted, explanation):
    BANK[level]['sa'].append({'type':'주관식','topic':topic,'kind':kind,'prompt':prompt,'answer':str(answer),'accepted':[str(x) for x in accepted],'explanation':explanation})


def neighbor_names(name, count=3):
    ix = next(i for i,x in enumerate(FUNCTIONS) if x[0] == name)
    picks = []
    for step in range(1, len(FUNCTIONS)):
        candidate = FUNCTIONS[(ix + step) % len(FUNCTIONS)][0]
        if candidate != name and candidate not in picks: picks.append(candidate)
        if len(picks) == count: break
    return picks

